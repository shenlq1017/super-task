//! httpd.conf 渲染（规格 §5.3 简化集）。
//!
//! 自包含最小 conf：ServerRoot/日志/PidFile 指向 `.supertask/gateway/`；
//! 最小 LoadModule 集（平台差异经 [`ApacheOptions`] 注入，不内置探测）；
//! ProxyPass 不剥前缀（与 nginx/caddy 同语义；`strip_prefix` 时用带尾斜杠
//! worker 显式剥除）；WebSocket 经 `ProxyPass … upgrade=websocket` 透传
//! （Apache 2.4.47+，本机校验失败会有明确 stderr）；CORS 用 `<Location>`
//! + `SetEnvIf` 白名单回显 + `mod_rewrite` preflight 204；静态站点
//! `DocumentRoot` + `Require all granted`；重定向 `Redirect`。

use crate::gateway::model::{GatewayCors, ResolvedGateway};

use super::{posix, sorted_locations};

